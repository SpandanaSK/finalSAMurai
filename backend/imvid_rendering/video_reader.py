"""
Simple Video Reader Module

This module provides functionality for extracting frames from video files with both
synchronous and asynchronous support.
"""

import cv2
import os
import logging
import asyncio
import threading
import concurrent.futures
from glob import glob
from pathlib import Path
from typing import Dict, List, Optional, Tuple, Any
from concurrent.futures import ThreadPoolExecutor

from backend.imvid_rendering.base_reader import ImageReader, ReaderStatus
from backend.imvid_rendering.base_reader import FileNotFoundError, FileReadError, FileFormatError
from backend.progress_manager.progress_manager import global_progress_manager
from backend.imvid_rendering.utils import (
    SUPPORTED_VIDEO_EXTENSIONS,
    normalize_read_file_output,
    get_output_dir,
    TMP_IMG_PATH
)

# Configure logging
logger = logging.getLogger(__name__)

# Constants
MAX_WORKERS = 4             # Maximum number of worker threads
FRAME_BATCH_SIZE = 250      # Number of frames to process in a batch
MAX_RETRY_ATTEMPTS = 3      # Maximum number of retry attempts for corrupted frames
FRAME_QUALITY = 95          # JPEG quality for extracted frames
FRAME_FILENAME_FORMAT = "{:05d}.png"  # Format for frame filenames


class SimpleVideoReader(ImageReader):
    """
    Simple reader for extracting frames from video files.
    """
    
    def __init__(self):
        """Initialize the video reader."""
        self.reader_name = 'SimpleVideoReader'
        self.cache = {}  # Cache for video metadata
        self._executor = ThreadPoolExecutor(max_workers=MAX_WORKERS)
        self._tasks = {}  # Track active extraction tasks
        
        # Get the shared event loop
        try:
            from backend.imvid_rendering.event_loop import get_event_loop
            self._event_loop = get_event_loop()
            logger.info(f"{self.reader_name}: Using shared event loop")
        except ImportError:
            # Fall back to standard asyncio behavior if our module is not available
            try:
                self._event_loop = asyncio.get_event_loop()
            except RuntimeError:
                self._event_loop = asyncio.new_event_loop()
                asyncio.set_event_loop(self._event_loop)
            logger.info(f"{self.reader_name}: Using standard event loop")

    def get_image_path(self, file_path: str, frame_num: int | None, extra_params: Dict[str, Any] | None) -> str:
        return get_output_dir(file_path, extra_params, out_dir=TMP_IMG_PATH)
    
    def __del__(self):
        """Clean up resources when the reader is destroyed."""
        try:
            # Cancel any running tasks
            for task_id, task in self._tasks.items():
                if not task.done():
                    task.cancel()
            
            # Don't stop the event loop as it's now shared
            
            # Shutdown the executor
            self._executor.shutdown(wait=False)
        except Exception as e:
            logger.error(f"Error during cleanup: {e}")
    
    # ------------------------
    # File Operations
    # ------------------------
    
    def validate_format(self, file_path: str) -> bool:
        """Validate that the file is a supported video format."""
        # Check if file exists
        if not os.path.exists(file_path):
            raise FileNotFoundError(file_path)
        
        # Skip extension check for files generated by our system
        if 'series_multiframe' in file_path:
            # Try to open the video file even if extension doesn't match
            try:
                cap = cv2.VideoCapture(file_path)
                if not cap.isOpened():
                    cap.release()
                    raise FileFormatError(file_path, "video", "Could not open video file")
                # Get basic properties to confirm it's valid
                frame_count = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))
                width = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
                height = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
                
                if frame_count <= 0 or width <= 0 or height <= 0:
                    logger.warning(f"Invalid video properties: frames={frame_count}, width={width}, height={height}")
                    cap.release()
                    raise FileFormatError(file_path, "video", "Invalid video properties")
                
                cap.release()
                logger.info(f"Validated video: {file_path} with {frame_count} frames ({width}x{height})")
                return True
            except Exception as e:
                if isinstance(e, FileFormatError):
                    raise
                logger.error(f"Error validating video: {e}")
                raise FileReadError(file_path, f"Error validating video file: {str(e)}")
        
        # For non-generated files, check extension
        if not any(file_path.lower().endswith(ext) for ext in SUPPORTED_VIDEO_EXTENSIONS):
            raise FileFormatError(file_path, "video", 
                                f"Unsupported video format. Supported: {', '.join(SUPPORTED_VIDEO_EXTENSIONS)}")
        
        # Try to open the video file
        try:
            cap = cv2.VideoCapture(file_path)
            if not cap.isOpened():
                cap.release()
                raise FileFormatError(file_path, "video", "Could not open video file")
            
            # Verify we can read at least one frame
            ret, frame = cap.read()
            if not ret or frame is None:
                logger.error(f"Could not read any frames from {file_path}")
                cap.release()
                raise FileFormatError(file_path, "video", "Could not read frames from video file")
                
            cap.release()
            return True
        except Exception as e:
            if isinstance(e, FileFormatError):
                raise
            logger.error(f"Error validating video file: {e}")
            raise FileReadError(file_path, f"Error validating video file: {str(e)}")
    
    def get_num_frames(self, file_path: str) -> int:
        """Get the number of frames in a video file."""
        self.validate_format(file_path)
        
        # Check cache first
        if file_path in self.cache and 'num_frames' in self.cache[file_path]:
            return self.cache[file_path]['num_frames']
        
        try:
            cap = cv2.VideoCapture(file_path)
            if not cap.isOpened():
                raise FileReadError(file_path, "Could not open video file")
                
            total_frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))
            cap.release()
            
            # Cache the result
            if file_path not in self.cache:
                self.cache[file_path] = {}
            self.cache[file_path]['num_frames'] = total_frames
            
            return total_frames
        except Exception as e:
            logger.error(f"Error getting frame count: {e}")
            raise FileReadError(file_path, f"Error getting frame count: {str(e)}")
    
    def get_fps(self, file_path: str) -> float:
        """Get the frames per second of a video file."""
        self.validate_format(file_path)
        
        # Check cache first
        if file_path in self.cache and 'fps' in self.cache[file_path]:
            return self.cache[file_path]['fps']
        
        try:
            cap = cv2.VideoCapture(file_path)
            fps = float(cap.get(cv2.CAP_PROP_FPS))
            cap.release()
            
            # Cache the result
            if file_path not in self.cache:
                self.cache[file_path] = {}
            self.cache[file_path]['fps'] = fps
            
            return fps
        except Exception as e:
            logger.error(f"Error getting FPS: {e}")
            raise FileReadError(file_path, f"Error getting FPS: {str(e)}")
    
    def get_image_dimensions(self, file_path: str) -> Tuple[int, int]:
        """Get the dimensions of video frames."""
        self.validate_format(file_path)
        
        # Check cache first
        if file_path in self.cache and 'dimensions' in self.cache[file_path]:
            return self.cache[file_path]['dimensions']
        
        try:
            cap = cv2.VideoCapture(file_path)
            width = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
            height = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
            cap.release()
            
            dimensions = (width, height)
            
            # Cache the result
            if file_path not in self.cache:
                self.cache[file_path] = {}
            self.cache[file_path]['dimensions'] = dimensions
            
            return dimensions
        except Exception as e:
            logger.error(f"Error getting dimensions: {e}")
            raise FileReadError(file_path, f"Error getting dimensions: {str(e)}")
    
    # ------------------------
    # Frame Extraction
    # ------------------------
    
    def get_existing_and_expected_frames(self, file_path: str, local_dir: str) -> Tuple[List[str], List[str]]:
        """Get lists of existing and expected frame files."""
        try:
            # Fast check for existing files first
            frame_files = sorted(glob(os.path.join(local_dir, '[0-9]*.png')))
            
            # If we found frame files, get the expected count
            if frame_files:
                try:
                    # Try to get frame count from the filenames
                    max_frame = 0
                    for f in frame_files:
                        basename = os.path.basename(f)
                        if basename.startswith('0') and basename.endswith('.png'):
                            try:
                                frame_num = int(basename.split('.')[0])
                                max_frame = max(max_frame, frame_num)
                            except ValueError:
                                pass
                    
                    if max_frame > 0:
                        # Add 1 because frame numbers are 0-indexed
                        expected_count = max_frame + 1
                        logger.info(f"Determined {expected_count} expected frames from existing files")
                        
                        # Create expected frame list
                        expected_frame_files = [
                            os.path.join(local_dir, FRAME_FILENAME_FORMAT.format(i)) 
                            for i in range(expected_count)
                        ]
                        
                        return frame_files, expected_frame_files
                except Exception as e:
                    logger.error(f"Error determining frame count from filenames: {e}")
            
            # Get total frame count using video metadata
            total_frames = self.get_num_frames(file_path)
            
            # Create list of expected frames
            expected_frame_files = [
                os.path.join(local_dir, FRAME_FILENAME_FORMAT.format(i)) 
                for i in range(total_frames)
            ]
            
            # Get existing frames using different patterns to be thorough
            patterns = [
                os.path.join(local_dir, '*.png'),          # All PNGs
                os.path.join(local_dir, '[0-9]*.png'),     # Numbered PNGs
                os.path.join(local_dir, '[0-9][0-9]*.png') # Double-digit PNGs
            ]
            
            existing_frames = []
            for pattern in patterns:
                existing_frames.extend(glob(pattern))
            
            # Remove duplicates and sort
            existing_frames = sorted(set(existing_frames))
            
            # Log the results
            logger.info(f"Found {len(existing_frames)} existing frames out of {len(expected_frame_files)} expected for {file_path}")
                
            return existing_frames, expected_frame_files
        except Exception as e:
            logger.error(f"Error getting frame lists: {e}")
            return [], []
    
    def _process_frame_batch(self, file_path: str, out_dir: str, start_idx: int, 
                           end_idx: int, task_id: str, total_frames: int) -> List[str]:
        """Process a batch of frames from the video."""
        extracted_frames = []
        try:
            logger.info(f"Processing frames {start_idx} to {end_idx-1} from {file_path}")
            cap = cv2.VideoCapture(file_path)
            
            if not cap.isOpened():
                logger.error(f"Could not open video file: {file_path}")
                return extracted_frames
                
            # Verify dimensions to help with debugging
            width = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
            height = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
            actual_frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))
            
            logger.info(f"Video properties: {width}x{height}, {actual_frames} frames, processing {end_idx-start_idx} frames")
            
            # Check if total frames is valid
            if total_frames <= 0 or actual_frames <= 0:
                logger.error(f"Invalid frame count: total={total_frames}, actual={actual_frames}")
                cap.release()
                return extracted_frames
                
            # Set initial position
            cap.set(cv2.CAP_PROP_POS_FRAMES, start_idx)
            
            for frame_idx in range(start_idx, end_idx):
                if frame_idx >= actual_frames:
                    logger.warning(f"Frame index {frame_idx} exceeds actual frame count {actual_frames}")
                    break
                    
                out_path = os.path.join(out_dir, FRAME_FILENAME_FORMAT.format(frame_idx))
                
                # Skip if frame already exists
                if os.path.exists(out_path) and os.path.getsize(out_path) > 0:
                    extracted_frames.append(out_path)
                    continue
                
                # Try to read the frame with retries for corrupted frames
                success = False
                for attempt in range(MAX_RETRY_ATTEMPTS):
                    ret, frame = cap.read()
                    if ret and frame is not None:
                        success = True
                        break
                    
                    # If frame read failed, try to seek to the next frame
                    if frame_idx + 1 < actual_frames:
                        logger.warning(f"Retry {attempt+1}/{MAX_RETRY_ATTEMPTS} for frame {frame_idx}")
                        cap.set(cv2.CAP_PROP_POS_FRAMES, frame_idx + 1)
                        frame_idx += 1
                    else:
                        logger.warning(f"End of video reached at frame {frame_idx}")
                        break
                
                if success:
                    # Save the frame
                    try:
                        cv2.imwrite(out_path, frame, [cv2.IMWRITE_JPEG_QUALITY, FRAME_QUALITY])
                        if os.path.exists(out_path) and os.path.getsize(out_path) > 0:
                            extracted_frames.append(out_path)
                        else:
                            logger.error(f"Frame {frame_idx} was not saved properly")
                    except Exception as e:
                        logger.error(f"Error saving frame {frame_idx}: {e}")
                else:
                    logger.error(f"Failed to extract frame {frame_idx} after {MAX_RETRY_ATTEMPTS} attempts")
                
                # Update progress
                if total_frames > 0 and task_id:
                    percent = min(int((frame_idx - start_idx + 1) / (end_idx - start_idx) * 100), 100)
                    self.update_task_status(
                        task_id,
                        'video',
                        ReaderStatus.VIDEO_EXTRACTING_FRAMES,
                        percent
                    )
            
            cap.release()
            logger.info(f"Extracted {len(extracted_frames)} frames out of {end_idx-start_idx} attempted")
            return extracted_frames
            
        except Exception as e:
            logger.error(f"Error processing batch {start_idx}-{end_idx}: {e}")
            return extracted_frames
    
    async def async_extract_frames(self, file_path: str, out_dir: str, task_id: str) -> List[str]:
        """Extract frames from a video file asynchronously."""
        try:
            # Update task status
            self.update_task_status(
                task_id,
                'video',
                ReaderStatus.VIDEO_EXTRACTION_STARTED,
                0
            )
            
            # Get total frames
            total_frames = self.get_num_frames(file_path)
            logger.info(f"Processing {total_frames} frames")
            
            # Process frames in batches
            all_extracted_frames = []
            batch_size = min(FRAME_BATCH_SIZE, max(50, total_frames // 20))
            
            for start_idx in range(0, total_frames, batch_size):
                end_idx = min(start_idx + batch_size, total_frames)
                
                # Process batch
                extracted_frames = await self._event_loop.run_in_executor(
                    self._executor,
                    self._process_frame_batch,
                    file_path, out_dir, start_idx, end_idx, task_id, total_frames
                )
                
                all_extracted_frames.extend(extracted_frames)
                
                # Update progress
                progress = min(int(end_idx / total_frames * 100), 99)
                self.update_task_status(
                    task_id,
                    'video',
                    ReaderStatus.VIDEO_EXTRACTING_FRAMES,
                    progress
                )
            
            # Mark as complete
            self.update_task_status(
                task_id,
                'video',
                ReaderStatus.VIDEO_EXTRACTING_COMPLETE,
                100
            )
            
            return all_extracted_frames
        except Exception as e:
            logger.error(f"Error extracting frames: {e}")
            self.update_task_status(
                task_id,
                'video',
                ReaderStatus.OPERATION_FAILED,
                -1
            )
            return []
    
    @normalize_read_file_output
    def read_file(self, file_path: str, frame_num: Optional[int] = None, 
                 store_images: bool = True, extra_params: Optional[Dict[str, Any]] = None, 
                 task_id: Optional[str] = None, local_dir: Optional[str] = None, 
                 async_read: bool = True) -> Dict[str, Any]:
        """Read a video file and extract frames."""
        try:
            # Special case ONLY for series_multiframe.mp4 files from ZIP extractions
            # Only apply this for files explicitly marked from_zip=True
            if 'series_multiframe.mp4' in file_path and '/extracted/' in file_path and extra_params and extra_params.get('from_zip'):
                logger.info(f"Special case: series_multiframe.mp4 from ZIP extraction: {file_path}")
                extract_dir = os.path.dirname(file_path)
                # Check if PNG files already exist in this directory
                png_files = sorted(glob(os.path.join(extract_dir, '*.png')))
                if png_files:
                    logger.info(f"Found {len(png_files)} existing PNG files, using directly instead of extracting from video")
                    # Create task if needed
                    if task_id is None:
                        task_id = global_progress_manager.create_task(file_path, extra_params)
                    # Mark as complete
                    self.update_task_status(task_id, 'video', ReaderStatus.VIDEO_EXTRACTING_COMPLETE, 100)
                    return png_files, png_files
            
            # Normal video processing path
            # Validate input
            self.validate_format(file_path)
            
            if not os.path.exists(file_path):
                task_id = global_progress_manager.create_task(file_path, extra_params)
                self.update_task_status(task_id, 'video', ReaderStatus.FILE_NOT_FOUND, -1)
                return task_id, {'video': ReaderStatus.FILE_NOT_FOUND}
            
            # Set up output directory
            if local_dir is None:
                local_dir = get_output_dir(file_path, extra_params, out_dir=TMP_IMG_PATH)
            Path(local_dir).mkdir(parents=True, exist_ok=True)
            
            # Get or create task
            if task_id is None:
                task_id = global_progress_manager.create_task(file_path, extra_params)
            
            # Get existing and expected frames
            existing_frames, expected_frames = self.get_existing_and_expected_frames(file_path, local_dir)
            
            # If we already have all expected frames, return them immediately
            if len(existing_frames) >= len(expected_frames) and expected_frames:
                logger.info(f"All {len(existing_frames)} frames already extracted for {file_path}")
                self.update_task_status(task_id, 'video', ReaderStatus.VIDEO_EXTRACTING_COMPLETE, 100)
                return existing_frames, expected_frames
            
            # Check if extraction is needed
            if len(existing_frames) < len(expected_frames):
                # Start extraction
                self.update_task_status(task_id, 'video', ReaderStatus.VIDEO_EXTRACTION_STARTED, 0)
                
                if async_read:
                    # Start async extraction
                    try:
                        # Create a future for the async task
                        future = asyncio.run_coroutine_threadsafe(
                            self.async_extract_frames(file_path, local_dir, task_id),
                            self._event_loop
                        )
                        
                        # Add callback for error handling
                        def on_task_done(future):
                            try:
                                future.result()
                                logger.info(f"Task {task_id} completed successfully")
                            except Exception as e:
                                logger.error(f"Task {task_id} failed: {e}")
                                self.update_task_status(task_id, 'video', ReaderStatus.OPERATION_FAILED, -1)
                        
                        future.add_done_callback(on_task_done)
                        
                        # Store task reference
                        self._tasks[task_id] = future
                        
                        # Return current state
                        existing_frames, expected_frames = self.get_existing_and_expected_frames(file_path, local_dir)

                        return existing_frames, expected_frames
                    except Exception as e:
                        logger.error(f"Failed to start async extraction: {e}")
                        raise
                else:
                    # Synchronous extraction
                    try:
                        # Run async task to completion with a timeout
                        future = asyncio.run_coroutine_threadsafe(
                            self.async_extract_frames(file_path, local_dir, task_id),
                            self._event_loop
                        )
                        
                        try:
                            # Add a timeout to prevent infinite waiting
                            extracted_frames = future.result(timeout=120)  # 2 minute timeout
                            logger.info(f"Synchronous extraction completed with {len(extracted_frames)} frames")
                        except concurrent.futures.TimeoutError:
                            logger.error(f"Timeout waiting for video extraction to complete")
                            self.update_task_status(task_id, 'video', ReaderStatus.OPERATION_FAILED, -1)
                            # Get whatever frames we have so far
                            existing_frames, expected_frames = self.get_existing_and_expected_frames(file_path, local_dir)
                            return existing_frames, expected_frames
                            
                        existing_frames, expected_frames = self.get_existing_and_expected_frames(file_path, local_dir)
                        return existing_frames, expected_frames
                    except Exception as e:
                        logger.error(f"Error in synchronous extraction: {e}")
                        raise
            else:
                # Extraction not needed
                self.update_task_status(task_id, 'video', ReaderStatus.VIDEO_EXTRACTING_COMPLETE, 100)
                return existing_frames, expected_frames
                
        except Exception as e:
            logger.error(f"Error reading file {file_path}: {e}")
            raise FileReadError(file_path, f"Error reading file: {str(e)}")
